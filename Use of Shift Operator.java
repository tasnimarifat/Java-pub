public class Main {
    public static void main(String[] args) {
        int a = 8;

        System.out.println("Original number = " + a);
        System.out.println("Left shift (a << 1) = " + (a << 1));
        System.out.println("Right shift (a >> 1) = " + (a >> 1));
        System.out.println("Unsigned right shift (a >>> 1) = " + (a >>> 1));
    }
}

